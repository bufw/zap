//! 统一的「面板托管配置」文件存储接口。
//!
//!
//! ```text
//! {ZAP_PATH}/data/conf/
//! └── <project>/
//!     ├── <file>.yaml          # 结构化模型（YAML，由面板维护，注释提示勿手改）
//!     ├── <file>.conf          # 渲染 / 生成的文本（可选）
//!     └── revisions/
//!         ├── index.yaml       # 历史版本元数据列表（按时间倒序来源）
//!         └── {id}.conf        # 每次生成 / 应用留痕的全文，供 diff 与回滚
//! ```

use std::path::{Path, PathBuf};
use std::sync::Arc;

use serde::Serialize;
use serde_json::Value;
use tokio::fs;
use tokio::sync::RwLock;

use crate::zap::ZapError;

/// 所有项目共享一把写锁：写文件是低频操作，单全局锁足够，且避免跨项目相互踩踏。
static WRITE_LOCK: std::sync::OnceLock<Arc<RwLock<()>>> = std::sync::OnceLock::new();

fn lock() -> &'static Arc<RwLock<()>> {
    WRITE_LOCK.get_or_init(|| Arc::new(RwLock::new(())))
}

fn zap_path() -> PathBuf {
    std::env::var("ZAP_PATH")
        .map(PathBuf::from)
        .unwrap_or_else(|_| PathBuf::from("/usr/local/zap"))
}

/// 所有配置项目的根目录：`{ZAP_PATH}/data/conf`
pub fn conf_root() -> PathBuf {
    zap_path().join("data/conf")
}

/// YAML 文件头部注释（提示这是面板维护的、手改可能被覆盖）。
const YAML_HEADER: &str = "# Generated by Zap , DO NOT EDIT\n";

/// 一个配置项目（如 `nginx`）在 `data/conf/<name>/` 下的文件仓库。
///
/// 同一进程内对同一 `name` 多次 `new` 得到彼此独立的结构体，但都指向同一目录、
/// 共享同一把全局写锁。
pub struct ProjectConf {
    dir: PathBuf,
}

impl ProjectConf {
    /// 用一个项目名（如 `nginx`）创建仓库，目录为 `data/conf/<name>`。
    pub fn new(name: &str) -> Self {
        let dir = conf_root().join(name);
        Self { dir }
    }

    /// 项目目录（如 `data/conf/nginx`）。
    pub fn dir(&self) -> &Path {
        &self.dir
    }

    fn revisions_dir(&self) -> PathBuf {
        self.dir.join("revisions")
    }

    fn revisions_index(&self) -> PathBuf {
        self.revisions_dir().join("index.yaml")
    }

    fn revision_file(&self, id: i64) -> PathBuf {
        self.revisions_dir().join(format!("{id}.conf"))
    }

    async fn ensure_dirs(&self) -> Result<(), ZapError> {
        fs::create_dir_all(&self.dir).await.map_err(|e| {
            ZapError::New(-1, format!("创建配置目录失败 {}: {e}", self.dir.display()))
        })?;
        fs::create_dir_all(self.revisions_dir())
            .await
            .map_err(|e| ZapError::New(-1, format!("创建历史版本目录失败: {e}")))?;
        Ok(())
    }

    // ── 结构化模型（YAML）──────────────────────────────────────

    /// 把结构化模型以 YAML 写入 `<file>`（如 `nginx_conf.yaml`）。
    pub async fn write_yaml(&self, file: &str, value: &Value) -> Result<(), ZapError> {
        let _guard = lock().write().await;
        self.ensure_dirs().await?;
        let mut yaml = serde_yaml::to_string(value)
            .map_err(|e| ZapError::New(-1, format!("序列化 YAML 失败: {e}")))?;
        if !yaml.starts_with('#') {
            yaml.insert_str(0, YAML_HEADER);
        }
        write_atomic(&self.dir.join(file), &yaml).await
    }

    /// 读取 `<file>` 的 YAML；文件不存在返回 `Ok(None)`。
    pub async fn read_yaml(&self, file: &str) -> Result<Option<Value>, ZapError> {
        let _guard = lock().read().await;
        let path = self.dir.join(file);
        read_yaml_opt(&path).await
    }

    // ── 渲染 / 生成文本（raw）──────────────────────────────────

    /// 把渲染出的文本写入 `<file>`（如 `nginx.conf` 生成件），供预览或落盘前对比。
    pub async fn write_raw(&self, file: &str, content: &str) -> Result<(), ZapError> {
        let _guard = lock().write().await;
        self.ensure_dirs().await?;
        write_atomic(&self.dir.join(file), content).await
    }

    /// 读取 `<file>` 的文本；文件不存在返回 `Ok(None)`。
    pub async fn read_raw(&self, file: &str) -> Result<Option<String>, ZapError> {
        let _guard = lock().read().await;
        let path = self.dir.join(file);
        match fs::read_to_string(&path).await {
            Ok(t) => Ok(Some(t)),
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(None),
            Err(e) => Err(ZapError::New(
                -1,
                format!("读取文件失败 {}: {e}", path.display()),
            )),
        }
    }

    // ── 历史版本（revisions）──────────────────────────────────

    /// 留存一次生成 / 应用的全文，返回版本 id（时间戳秒）。保留最近 30 条。
    pub async fn save_revision(
        &self,
        content: &str,
        actor: &str,
        ok: bool,
    ) -> Result<i64, ZapError> {
        let _guard = lock().write().await;
        self.ensure_dirs().await?;

        let meta = RevisionMeta::new(actor.to_string(), ok);
        let id = meta.id;
        write_atomic(&self.revision_file(id), content).await?;

        let mut index = self.read_index().await?;
        index.push(meta);
        if index.len() > 30 {
            let old = index.drain(..index.len() - 30).collect::<Vec<_>>();
            for m in old {
                let _ = fs::remove_file(self.revision_file(m.id)).await;
            }
        }
        self.write_index(&index).await?;
        Ok(id)
    }

    /// 最近 30 条历史版本元数据（按时间倒序）。
    pub async fn list_revisions(&self) -> Result<Vec<RevisionMeta>, ZapError> {
        let _guard = lock().read().await;
        let mut index = self.read_index().await?;
        index.reverse();
        Ok(index)
    }

    /// 读取某一历史版本的全文。
    pub async fn get_revision(&self, id: i64) -> Result<Option<String>, ZapError> {
        let _guard = lock().read().await;
        match fs::read_to_string(self.revision_file(id)).await {
            Ok(t) => Ok(Some(t)),
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(None),
            Err(e) => Err(ZapError::New(-1, format!("读取历史版本失败: {e}"))),
        }
    }

    // ── 内部 ───────────────────────────────────────────────────

    async fn read_index(&self) -> Result<Vec<RevisionMeta>, ZapError> {
        let path = self.revisions_index();
        let text = match fs::read_to_string(&path).await {
            Ok(t) => t,
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(Vec::new()),
            Err(e) => return Err(ZapError::New(-1, format!("读取历史版本索引失败: {e}"))),
        };
        serde_yaml::from_str(&text)
            .map_err(|e| ZapError::New(-1, format!("解析历史版本索引失败: {e}")))
    }

    async fn write_index(&self, index: &[RevisionMeta]) -> Result<(), ZapError> {
        let yaml = serde_yaml::to_string(index)
            .map_err(|e| ZapError::New(-1, format!("序列化历史版本索引失败: {e}")))?;
        write_atomic(&self.revisions_index(), &yaml).await
    }
}

/// 历史版本元数据。
#[derive(Debug, Clone, Serialize, serde::Deserialize)]
pub struct RevisionMeta {
    pub id: i64,
    pub actor: String,
    pub ok: bool,
    #[serde(rename = "created_at")]
    pub created_at: i64,
}

impl RevisionMeta {
    /// `id` 用时间戳（秒），与历史表自增 id 不冲突且天然有序。
    fn new(actor: String, ok: bool) -> Self {
        let created_at = chrono::Utc::now().timestamp();
        Self {
            id: created_at,
            actor,
            ok,
            created_at,
        }
    }
}

/// 原子写：`临时文件 + rename`，避免半截文件被读到。
async fn write_atomic(path: &Path, content: &str) -> Result<(), ZapError> {
    let tmp = path.with_extension("tmp");
    fs::write(&tmp, content)
        .await
        .map_err(|e| ZapError::New(-1, format!("写入临时文件失败 {}: {e}", tmp.display())))?;
    fs::rename(&tmp, path)
        .await
        .map_err(|e| ZapError::New(-1, format!("原子替换文件失败 {}: {e}", path.display())))?;
    Ok(())
}

/// 读取并解析 YAML 文件；文件不存在返回 `Ok(None)`。
async fn read_yaml_opt(path: &Path) -> Result<Option<Value>, ZapError> {
    let text = match fs::read_to_string(path).await {
        Ok(t) => t,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(None),
        Err(e) => {
            return Err(ZapError::New(
                -1,
                format!("读取 YAML 失败 {}: {e}", path.display()),
            ));
        }
    };
    let value: Value = serde_yaml::from_str(&text)
        .map_err(|e| ZapError::New(-1, format!("解析 YAML 失败 {}: {e}", path.display())))?;
    Ok(Some(value))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn revision_meta_new_uses_timestamp() {
        let m = RevisionMeta::new("admin".into(), true);
        assert_eq!(m.id, m.created_at);
        assert!(m.id > 1_700_000_000);
    }

    #[test]
    fn safe_yaml_roundtrip() {
        let v: Value = serde_yaml::from_str(
            r#"
ver: 1
adopted: true
general:
  user: www
events:
  worker_connections: 1024
"#,
        )
        .unwrap();
        assert_eq!(v["ver"].as_i64(), Some(1));
        assert_eq!(v["general"]["user"].as_str(), Some("www"));
    }
}
